#!/usr/bin/env node
// Renders the plugin overview in README.md from lithe-plugin-index.json, so the
// cards always match what Lithe shows in its marketplace. Only the block between
// the `plugins:start` / `plugins:end` markers is generated; edit the rest by hand.
// The `Sync README` workflow runs this after every change on main.
//
// Usage: node scripts/render-readme.mjs [--check]
//   --check  exit 1 when README.md is out of date instead of rewriting it.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const START = "<!-- plugins:start (generated by scripts/render-readme.mjs, do not edit) -->";
export const END = "<!-- plugins:end -->";
const DEFAULT_ICON = "assets/plugin-default.svg";
const COLUMNS = 2;
const DESCRIPTION_LIMIT = 110;

// Tag → overview category. The first matching tag wins; anything else is “其他”.
const CATEGORIES = [
  ["language", "语言支持"],
  ["build", "构建工具"],
  ["vcs", "版本控制"],
  ["theme", "主题"],
  ["tool", "工具"],
];
const OS_LABELS = { darwin: "macOS", windows: "Windows", linux: "Linux" };

const escapeHTML = (text) =>
  String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function categoryOf(entry) {
  const tags = entry.tags ?? [];
  return CATEGORIES.find(([tag]) => tags.includes(tag))?.[1] ?? "其他";
}

/** Operating systems served by the newest version, in a stable order. */
export function systemsOf(version) {
  const systems = new Set(version.downloads.flatMap((download) => download.platforms.map((platform) => platform.split("-")[0])));
  return Object.keys(OS_LABELS).filter((os) => systems.has(os)).map((os) => OS_LABELS[os]);
}

export function truncate(text, limit = DESCRIPTION_LIMIT) {
  const chars = [...text];
  return chars.length <= limit ? text : `${chars.slice(0, limit).join("").trimEnd()}…`;
}

function repositoryPath(url) {
  return new URL(url).pathname.replace(/^\/|\/$/g, "");
}

export function renderCard(entry) {
  const latest = entry.versions[0];
  const description = entry.localizedDescriptions?.["zh-Hans"] ?? entry.description;
  const requires = Object.keys(latest.requires ?? {});
  const meta = [
    escapeHTML(entry.author),
    `v${escapeHTML(latest.version)}`,
    `API ${latest.pluginAPIVersion}${requires.length ? `（需 ${requires.map(escapeHTML).join("、")}）` : ""}`,
  ].join(" · ");
  const tags = (entry.tags ?? []).map((tag) => `<code>${escapeHTML(tag)}</code>`).join(" ");
  const repo = repositoryPath(entry.repository);
  const stars = `<img src="https://img.shields.io/github/stars/${repo}?style=flat&label=stars&logo=github" alt="GitHub stars">`;
  return [
    `<td width="${100 / COLUMNS}%" valign="top">`,
    `<h3><img src="${escapeHTML(entry.icon ?? DEFAULT_ICON)}" width="28" height="28" alt=""> <a href="${escapeHTML(entry.repository)}">${escapeHTML(entry.name)}</a></h3>`,
    `<p><sub>${meta}</sub></p>`,
    `<p>${escapeHTML(truncate(description))}</p>`,
    `<p>🏷️ ${escapeHTML(categoryOf(entry))} · 💻 ${systemsOf(latest).join(" / ")} · ${stars}</p>`,
    tags ? `<p>${tags}</p>` : "",
    `</td>`,
  ].filter(Boolean).join("\n");
}

export function renderOverview(index) {
  const plugins = [...index.plugins].sort((a, b) => a.name.localeCompare(b.name, "en"));
  const counts = new Map();
  for (const entry of plugins) counts.set(categoryOf(entry), (counts.get(categoryOf(entry)) ?? 0) + 1);
  const summary = [`**全部 · ${plugins.length}**`, ...[...counts].map(([name, count]) => `${name} · ${count}`)].join("　｜　");

  const rows = [];
  for (let i = 0; i < plugins.length; i += COLUMNS) {
    const cells = plugins.slice(i, i + COLUMNS).map(renderCard);
    while (cells.length < COLUMNS) cells.push(`<td width="${100 / COLUMNS}%"></td>`);
    rows.push(`<tr>\n${cells.join("\n")}\n</tr>`);
  }
  return [START, "", summary, "", "<table>", ...rows, "</table>", "", END].join("\n");
}

export function renderReadme(readme, index) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md must contain the plugins:start and plugins:end markers in order");
  }
  return readme.slice(0, start) + renderOverview(index) + readme.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const readmeURL = new URL("../README.md", import.meta.url);
  const index = JSON.parse(readFileSync(new URL("../lithe-plugin-index.json", import.meta.url), "utf8"));
  const current = readFileSync(readmeURL, "utf8");
  const next = renderReadme(current, index);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("README.md plugin overview is out of date. Run: node scripts/render-readme.mjs");
      process.exit(1);
    }
  } else if (next !== current) {
    writeFileSync(readmeURL, next);
    console.log("README.md plugin overview updated.");
  }
}
